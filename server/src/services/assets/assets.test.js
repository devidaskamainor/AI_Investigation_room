import { beforeAll, beforeEach, afterAll, describe, it, expect, vi } from 'vitest';
import request from 'supertest';
import session from 'express-session';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { testDatabase, testEnv } from '../../../test/database.js';
import { MockGeminiProvider } from '../../../test/fixtures/case.js';
import {
  MockImageProvider,
  MemoryStorageProvider,
  TEST_PNG,
} from '../../../test/fixtures/assets.js';
import {
  User,
  Mystery,
  MysterySolution,
  Suspect,
  Evidence,
  GenerationJob,
  Asset,
  InvestigationProgress,
  ensureIndexes,
} from '../../models/index.js';
import { createMystery } from '../mystery/creation.service.js';
import { claimJob } from '../../jobs/queue.js';
import { runJob } from '../generation/pipeline.js';
import { assetGenerator, readAsset, deleteMystery, validImage } from './assets.service.js';
import { LocalStorageProvider } from './storage.provider.js';
import { createApp } from '../../app.js';
import { ProviderError } from '../ai/retry.js';
import { CloudflareImageProvider } from '../ai/cloudflare.provider.js';
describe('M5 protected evidence assets', () => {
  let db, user, storage;
  beforeAll(async () => {
    db = await testDatabase();
    await ensureIndexes();
  });
  afterAll(async () => {
    await db.close();
  });
  beforeEach(async () => {
    await Promise.all(
      [
        User,
        Mystery,
        MysterySolution,
        Suspect,
        Evidence,
        GenerationJob,
        Asset,
        InvestigationProgress,
      ].map((m) => m.deleteMany({})),
    );
    user = await User.create({
      name: 'Detective',
      email: 'assets@example.test',
      passwordHash: 'test',
    });
    storage = new MemoryStorageProvider();
  });
  async function generate(imageProvider = new MockImageProvider()) {
    await createMystery(
      String(user._id),
      {
        scenario: 'A sculpture vanishes during a private gallery exhibition.',
        difficulty: 'easy',
        mysteryType: 'theft',
        suspectCount: 3,
      },
      'assets-key-0001',
      testEnv,
    );
    const job = await claimJob('assets-worker');
    await runJob(job, {
      env: testEnv,
      provider: new MockGeminiProvider(),
      generateAssets: assetGenerator(testEnv, imageProvider, storage),
    });
    return job;
  }
  it('AC-19 all published assets resolve; no public or cross-user access', async () => {
    const job = await generate(),
      m = await Mystery.findById(job.mysteryId);
    expect(m.status).toBe('ready');
    const assets = await Asset.find({ mysteryId: m._id });
    expect(assets).toHaveLength(8);
    for (const asset of assets) {
      expect(await storage.exists(asset.storageKey)).toBe(true);
      expect((await readAsset(String(user._id), asset._id, storage)).buffer).toEqual(TEST_PNG);
      await expect(readAsset('111111111111111111111111', asset._id, storage)).rejects.toMatchObject(
        { status: 404 },
      );
    }
    const app = createApp(
      { ...testEnv, MONGODB_URI: db.uri },
      { sessionStore: new session.MemoryStore(), storage, rateLimits: false },
    );
    expect((await request(app).get(`/api/v1/assets/${assets[0]._id}`)).status).toBe(401);
  });
  it('publishes and privately serves assets generated by the Cloudflare adapter', async () => {
    const fetcher = vi.fn(async () =>
      Response.json({ success: true, result: { image: TEST_PNG.toString('base64') } }),
    );
    const job = await generate(
      new CloudflareImageProvider(
        {
          ...testEnv,
          CLOUDFLARE_ACCOUNT_ID: 'a'.repeat(32),
          CLOUDFLARE_API_TOKEN: 'test-cloudflare-token',
          CLOUDFLARE_IMAGE_MODEL: '@cf/black-forest-labs/flux-1-schnell',
        },
        { fetch: fetcher },
      ),
    );
    expect((await Mystery.findById(job.mysteryId)).status).toBe('ready');
    expect(fetcher).toHaveBeenCalledTimes(8);
    const assets = await Asset.find({ mysteryId: job.mysteryId });
    expect(assets).toHaveLength(8);
    for (const asset of assets)
      expect((await readAsset(String(user._id), asset._id, storage)).buffer).toEqual(TEST_PNG);
  });
  it('AC-19 a failed required image prevents publication', async () => {
    const job = await generate({
      generate: async () => {
        throw new Error('private provider details');
      },
    });
    expect((await Mystery.findById(job.mysteryId)).status).toBe('failed');
    expect((await GenerationJob.findById(job._id)).errorCode).toBe('ASSET_FAILED');
  });
  it('reports an image provider quota failure without publishing a partial case', async () => {
    const job = await generate({
      generate: async () => {
        throw new ProviderError('PROVIDER_RATE_LIMIT');
      },
    });
    const result = await GenerationJob.findById(job._id);
    expect(result.status).toBe('failed');
    expect(result.errorCode).toBe('ASSET_QUOTA_EXCEEDED');
    expect(result.safeErrorMessage).toContain('quota');
    expect((await Mystery.findById(job.mysteryId)).status).toBe('failed');
  });
  it('FR-62 deleting during an in-flight image write leaves no orphan file', async () => {
    await createMystery(
      String(user._id),
      {
        scenario: 'A sculpture vanishes during a private gallery exhibition.',
        difficulty: 'easy',
        mysteryType: 'theft',
        suspectCount: 3,
      },
      'delete-race-0001',
      testEnv,
    );
    const job = await claimJob('deletion-race-worker');
    let release, signalStarted;
    const blocked = new Promise((resolve) => {
        release = resolve;
      }),
      started = new Promise((resolve) => {
        signalStarted = resolve;
      }),
      put = storage.put.bind(storage);
    storage.put = async (key, buffer) => {
      await put(key, buffer);
      signalStarted();
      await blocked;
    };
    const running = runJob(job, {
      env: testEnv,
      provider: new MockGeminiProvider(),
      generateAssets: assetGenerator(testEnv, new MockImageProvider(), storage),
    });
    await started;
    await deleteMystery(String(user._id), job.mysteryId, storage);
    release();
    expect(await running).toBe(false);
    await vi.waitFor(async () => {
      expect(storage.files.size).toBe(0);
      expect(await Asset.countDocuments({ mysteryId: job.mysteryId })).toBe(0);
    });
  });
  it('FR-62 cascade deletes only the owned case and its stored files', async () => {
    const job = await generate(),
      other = await Mystery.create({
        ownerId: '111111111111111111111111',
        title: 'Other owner',
        status: 'ready',
      });
    await expect(
      deleteMystery('111111111111111111111111', job.mysteryId, storage),
    ).rejects.toMatchObject({ status: 404 });
    await deleteMystery(String(user._id), job.mysteryId, storage);
    for (const model of [Mystery, Suspect, Evidence, MysterySolution, GenerationJob, Asset])
      expect(
        await model.countDocuments(
          model === Mystery ? { _id: job.mysteryId } : { mysteryId: job.mysteryId },
        ),
      ).toBe(0);
    expect(storage.files.size).toBe(0);
    expect(await Mystery.findById(other._id)).toBeTruthy();
  });
  it('rejects non-image content and HTML masquerading as PNG', () => {
    expect(validImage(Buffer.from('<svg><script>alert(1)</script></svg>'), 'image/png')).toBe(
      false,
    );
    expect(validImage(TEST_PNG, 'image/png')).toBe(true);
  });
  it('local storage confines keys and supports atomic write/read/delete', async () => {
    const root = await mkdtemp(join(tmpdir(), 'mystery-storage-')),
      local = new LocalStorageProvider(root),
      key = '111111111111111111111111/222222222222222222222222.png';
    try {
      expect(() => local.path('../../secrets')).toThrow();
      await local.put(key, TEST_PNG);
      expect(await local.get(key)).toEqual(TEST_PNG);
      await local.delete(key);
      expect(await local.exists(key)).toBe(false);
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });
});
